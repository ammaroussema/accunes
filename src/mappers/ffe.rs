pub struct MapperFfe {
    pub cfg: FfeConfig,
    pub mc1_mode: u8,
    pub mc2_mode: u8,
    pub smc_mode: u8,
    pub latch: u8,
    pub lock_chr: bool,

    pub prg_8k: [u8; 4],
    pub chr_1k: [u8; 12],
    pub latch_mmc4: [u8; 2],

    pub smc_irq: bool,
    pub smc_prev_pa: u16,
    pub smc_counter: i16,

    pub fds_io: u8,
    pub fds_counter: i16,

    pub scratch_ram: [u8; 4096],
    pub irq_pending: bool,
    pub irq_ack: bool,
    pub initialized: bool,
}

impl MapperFfe {
    pub fn default_mc1_mode(cfg: &FfeConfig) -> u8 {
        let submapper = match cfg.variant {
            FfeVariant::Mapper6(sub) => sub,
            FfeVariant::Mapper8 => 4,
            FfeVariant::Mapper12 => 1,
            FfeVariant::Mapper17(_) => 1,
        };
        let mirror_bits = if cfg.vertical_mirroring { 0x01 } else { 0x11 };
        (submapper << 5) | mirror_bits | 0x02
    }

    pub fn default_mc2_mode(cfg: &FfeConfig) -> u8 {
        match cfg.variant {
            FfeVariant::Mapper12 | FfeVariant::Mapper17(_) => 0x00,
            _ => 0x03,
        }
    }

    pub fn default_smc_mode(cfg: &FfeConfig) -> u8 {
        match cfg.variant {
            FfeVariant::Mapper17(_) => 0x47,
            _ => 0x42,
        }
    }

    pub fn new(cfg: FfeConfig) -> Self {
        let mc1_mode = Self::default_mc1_mode(&cfg);
        let mc2_mode = Self::default_mc2_mode(&cfg);
        let smc_mode = Self::default_smc_mode(&cfg);

        let mut scratch_ram = [0u8; 4096];
        scratch_ram.copy_from_slice(&SMC5000);

        let mut s = Self {
            cfg,
            mc1_mode,
            mc2_mode,
            smc_mode,
            latch: 0,
            lock_chr: false,
            prg_8k: [0, 1, 2, 3],
            chr_1k: [0, 1, 2, 3, 4, 5, 6, 7, 0, 1, 2, 3],
            latch_mmc4: [0; 2],
            smc_irq: false,
            smc_prev_pa: 0,
            smc_counter: 0,
            fds_io: 0,
            fds_counter: 0,
            scratch_ram,
            irq_pending: false,
            irq_ack: false,
            initialized: false,
        };
        s.init_banks(16);
        s
    }

    fn init_banks(&mut self, num_prg_8k: usize) {
        for bank in 0..4 {
            self.prg_8k[3 - bank] = num_prg_8k.saturating_sub(bank + 1) as u8;
        }
        for bank in 0..8 {
            self.chr_1k[bank] = bank as u8;
        }
    }

    fn fetch_prg_byte(&self, cart: &Cartridge, address: u16) -> u8 {
        let prg_len = cart.prg_rom.len();
        if prg_len == 0 {
            return 0;
        }
        let offset = self.get_prg_offset(address, prg_len);
        cart.prg_rom[offset % prg_len]
    }

    pub fn do_reset_with_cart(&mut self, cart: &mut Cartridge) {
        self.mc1_mode = Self::default_mc1_mode(&self.cfg);
        self.mc2_mode = Self::default_mc2_mode(&self.cfg);
        self.smc_mode = Self::default_smc_mode(&self.cfg);
        self.latch = 0;
        self.lock_chr = false;
        self.latch_mmc4 = [0; 2];
        self.smc_irq = false;
        self.smc_prev_pa = 0;
        self.smc_counter = 0;
        self.fds_io = 0;
        self.fds_counter = 0;
        self.irq_pending = false;
        self.irq_ack = false;

        if self.cfg.variant == FfeVariant::Mapper12 {
            if !cart.chr_rom.is_empty() {
                if cart.prg_rom.len() < 0x80000 {
                    cart.prg_rom.resize(0x80000, 0);
                }
                let copy_len = cart.chr_rom.len().min(0x40000);
                cart.prg_rom[0x40000..0x40000 + copy_len].copy_from_slice(&cart.chr_rom[..copy_len]);
                cart.chr_rom.clear();
                cart.using_chr_ram = true;
            }
        }

        if !cart.chr_rom.is_empty() {
            let target_len = (32 * 1024).max(cart.chr_rom.len());
            if cart.chr_ram.len() < target_len {
                cart.chr_ram.resize(target_len, 0);
            }
            let chr_len = cart.chr_rom.len();
            let ram_len = cart.chr_ram.len();
            for i in 0..ram_len {
                cart.chr_ram[i] = cart.chr_rom[i % chr_len];
            }
            cart.using_chr_ram = true;
        }
        if cart.chr_ram.len() < 0x2000 {
            cart.chr_ram.resize(0x2000, 0);
        }

        let num_prg_8k = (cart.prg_rom.len() / 0x2000).max(4);
        self.init_banks(num_prg_8k);

        self.scratch_ram.copy_from_slice(&SMC5000);
        if !cart.prg_rom.is_empty() {
            let nmi_low = self.fetch_prg_byte(cart, 0xFFFA);
            let nmi_high = self.fetch_prg_byte(cart, 0xFFFB);
            self.scratch_ram[0x4F] = nmi_low;
            self.scratch_ram[0x50] = nmi_high;
        }

        let trainer_data = if !self.cfg.trainer.is_empty() {
            &self.cfg.trainer[..]
        } else if !cart.trainer.is_empty() {
            &cart.trainer[..]
        } else if !cart.misc_rom.is_empty() && cart.misc_rom.len() <= 512 {
            &cart.misc_rom[..]
        } else {
            &[]
        };

        if !trainer_data.is_empty() {
            let is_m17 = matches!(self.cfg.variant, FfeVariant::Mapper17(_));
            let submapper = match self.cfg.variant {
                FfeVariant::Mapper17(s) => s,
                _ => 0,
            };
            let trainer_addr = if !is_m17 {
                0x7000
            } else if submapper == 0 {
                0x7000
            } else {
                ((submapper as u16) << 8) | 0x5C00
            };

            let len = trainer_data.len().min(512);
            if trainer_addr < 0x6000 {
                let off = (trainer_addr & 0xF00) as usize;
                if off + len <= self.scratch_ram.len() {
                    self.scratch_ram[off..off + len].copy_from_slice(&trainer_data[..len]);
                }
            } else {
                if cart.prg_ram.len() < 0x2000 {
                    cart.prg_ram.resize(0x2000, 0);
                }
                let off = (trainer_addr & 0x1F00) as usize;
                if off + len <= cart.prg_ram.len() {
                    cart.prg_ram[off..off + len].copy_from_slice(&trainer_data[..len]);
                }
            }
            self.cfg.has_trainer = true;
        }

        self.initialized = true;
    }

    fn ensure_init(&mut self, cart: &mut Cartridge) {
        if self.initialized {
            return;
        }
        self.do_reset_with_cart(cart);
    }

    fn get_prg_offset(&self, address: u16, prg_len: usize) -> usize {
        if (!self.mc2_mode & 0x01) != 0 {
            let bank_idx = ((address - 0x8000) >> 13) as usize; 
            let bank = self.prg_8k[bank_idx] as usize;
            let banks_8k = (prg_len / 0x2000).max(1);
            (bank % banks_8k) * 0x2000 + (address as usize & 0x1FFF)
        } else {
            let banks_16k = (prg_len / 0x4000).max(1);
            let banks_32k = (prg_len / 0x8000).max(1);
            match self.mc1_mode >> 5 {
                0 => {
                    let bank = if address < 0xC000 {
                        (self.latch & 7) as usize % banks_16k
                    } else {
                        7 % banks_16k
                    };
                    bank * 0x4000 + (address as usize & 0x3FFF)
                }
                1 => {
                    let bank = if address < 0xC000 {
                        ((self.latch >> 2) & 15) as usize % banks_16k
                    } else {
                        7 % banks_16k
                    };
                    bank * 0x4000 + (address as usize & 0x3FFF)
                }
                2 => {
                    let bank = if address < 0xC000 {
                        (self.latch & 15) as usize % banks_16k
                    } else {
                        15 % banks_16k
                    };
                    bank * 0x4000 + (address as usize & 0x3FFF)
                }
                3 => {
                    let bank = if address < 0xC000 {
                        15 % banks_16k
                    } else {
                        (self.latch & 15) as usize % banks_16k
                    };
                    bank * 0x4000 + (address as usize & 0x3FFF)
                }
                4 => {
                    let bank = ((self.latch >> 4) & 3) as usize % banks_32k;
                    bank * 0x8000 + (address as usize & 0x7FFF)
                }
                5 | 6 | 7 | _ => {
                    let bank = 3 % banks_32k;
                    bank * 0x8000 + (address as usize & 0x7FFF)
                }
            }
        }
    }

    fn ciram_offset_mode(&self, address: u16) -> usize {
        let off = (address & 0x03FF) as usize;
        let slot = ((address >> 10) & 3) as usize;
        match self.mc1_mode & 0x11 {
            0x00 => off,
            0x10 => 0x400 | off,
            0x01 => {
                if (slot & 1) == 0 { off } else { 0x400 | off }
            }
            0x11 | _ => {
                if slot >= 2 { 0x400 | off } else { off }
            }
        }
    }

    fn get_chr_1k_bank(&self, address: u16) -> usize {
        if (self.smc_mode & 0x01) != 0 {
            if (self.smc_mode & 0x04) != 0 {
                let bank = (address >> 10) as usize;
                self.chr_1k[bank.min(11)] as usize
            } else {
                let half = ((address >> 12) & 1) as usize;
                let reg_idx = (half * 4) | (self.latch_mmc4[half] as usize);
                let bank_4k = (self.chr_1k[reg_idx.min(11)] >> 2) as usize;
                let bank_1k_offset = ((address >> 10) & 3) as usize;
                bank_4k * 4 + bank_1k_offset
            }
        } else {
            let page_8k = match self.mc1_mode >> 5 {
                0 | 2 => 0,
                1 | 4 | 5 => (self.latch & 3) as usize,
                3 => ((self.latch >> 4) & 3) as usize,
                6 => (self.latch & 1) as usize,
                7 | _ => 3,
            };
            let bank_1k_offset = ((address >> 10) & 7) as usize;
            page_8k * 8 + bank_1k_offset
        }
    }

    fn clock_smc_counter(&mut self) {
        if self.smc_irq {
            if self.smc_counter == -1 {
                self.smc_irq = false;
                self.irq_pending = true;
            } else {
                self.smc_counter = self.smc_counter.wrapping_add(1);
            }
        }
    }
}

impl Mapper for MapperFfe {
    fn reset(&mut self) {
        self.mc1_mode = Self::default_mc1_mode(&self.cfg);
        self.mc2_mode = Self::default_mc2_mode(&self.cfg);
        self.smc_mode = Self::default_smc_mode(&self.cfg);
        self.latch = 0;
        self.lock_chr = false;
        self.init_banks(16);
        self.scratch_ram.copy_from_slice(&SMC5000);
        self.latch_mmc4 = [0; 2];
        self.smc_irq = false;
        self.smc_prev_pa = 0;
        self.smc_counter = 0;
        self.fds_io = 0;
        self.fds_counter = 0;
        self.irq_pending = false;
        self.irq_ack = false;
    }

    fn reset_power_cycle(&mut self) {
        self.reset();
        self.initialized = false;
    }

    fn reset_with_cart(&mut self, cart: &mut Cartridge) {
        self.do_reset_with_cart(cart);
    }

    fn initial_pc(&self) -> Option<u16> {
        if self.cfg.has_trainer {
            match self.cfg.variant {
                FfeVariant::Mapper17(submapper) => {
                    let trainer_addr = if submapper == 0 {
                        0x7000
                    } else {
                        ((submapper as u16) << 8) | 0x5C00
                    };
                    Some(trainer_addr)
                }
                _ => Some(0x5000),
            }
        } else {
            None
        }
    }

    fn fetch_prg(&mut self, cart: &Cartridge, address: u16) -> FetchResult {
        if (0x5000..0x6000).contains(&address) {
            return FetchResult {
                data: self.scratch_ram[(address - 0x5000) as usize],
                driven: true,
            };
        }
        if (0x6000..0x8000).contains(&address) {
            if cart.prg_ram.is_empty() {
                return FetchResult { data: 0, driven: false };
            }
            let offset = (address - 0x6000) as usize % cart.prg_ram.len();
            return FetchResult { data: cart.prg_ram[offset], driven: true };
        }
        if address == 0x4500 {
            return FetchResult { data: self.smc_mode, driven: true };
        }
        if address >= 0x8000 {
            if matches!(self.cfg.variant, FfeVariant::Mapper17(_)) && (address == 0xFFFA || address == 0xFFFB) {
                return FetchResult {
                    data: if address == 0xFFFA { 0x32 } else { 0x50 },
                    driven: true,
                };
            }
            let prg_len = cart.prg_rom.len();
            if prg_len == 0 {
                return FetchResult { data: 0, driven: true };
            }
            let offset = self.get_prg_offset(address, prg_len);
            return FetchResult {
                data: cart.prg_rom[offset % prg_len],
                driven: true,
            };
        }
        FetchResult { data: 0, driven: false }
    }

    fn store_prg(&mut self, cart: &mut Cartridge, address: u16, data: u8) {
        self.ensure_init(cart);

        if address == 0x4024 {
            self.irq_ack = true;
            self.irq_pending = false;
        } else if address == 0x4025 {
            self.irq_ack = true;
            self.irq_pending = false;
            if !self.smc_irq {
                self.fds_io = data;
                if (data & 0x42) != 0 {
                    self.fds_counter = 0;
                }
            }
        } else if (0x42FC..=0x42FF).contains(&address) {
            self.mc1_mode = (data & 0xF0) | ((address & 3) as u8);
            if self.mc1_mode >= 0x80 {
                self.lock_chr = false;
            }
        } else if (0x43FC..=0x43FF).contains(&address) {
            self.mc2_mode = (data & 0xF0) | ((address & 3) as u8);
            self.latch = data;
        } else if address == 0x4500 {
            self.smc_mode = data;
        } else if address == 0x4501 {
            self.smc_irq = false;
            self.irq_ack = true;
            self.irq_pending = false;
        } else if address == 0x4502 {
            self.smc_counter = ((self.smc_counter as u16 & 0xFF00) | (data as u16)) as i16;
            self.irq_ack = true;
            self.irq_pending = false;
        } else if address == 0x4503 {
            self.smc_irq = true;
            self.smc_counter = ((self.smc_counter as u16 & 0x00FF) | ((data as u16) << 8)) as i16;
            self.irq_ack = true;
            self.irq_pending = false;
        } else if (0x4504..=0x4507).contains(&address) {
            let val = if (self.mc2_mode & 0x02) != 0 { data >> 2 } else { data };
            self.prg_8k[(address & 3) as usize] = val;
        } else if (0x4510..=0x451B).contains(&address) {
            self.chr_1k[(address & 0x0F) as usize] = data;
        } else if (0x5000..0x6000).contains(&address) {
            self.scratch_ram[(address - 0x5000) as usize] = data;
        } else if (0x6000..0x8000).contains(&address) {
            if !cart.prg_ram.is_empty() {
                let off = (address - 0x6000) as usize % cart.prg_ram.len();
                cart.prg_ram[off] = data;
            }
        } else if address >= 0x8000 {
            if (self.mc1_mode & 0x02) != 0 {
                self.latch = data;
                if (self.mc2_mode & 0x03) != 0 {
                    let bank = ((address - 0x8000) >> 13) as usize;
                    self.prg_8k[bank] = data >> 2;
                }
            } else {
                if !cart.prg_rom.is_empty() {
                    let prg_len = cart.prg_rom.len();
                    let offset = self.get_prg_offset(address, prg_len);
                    cart.prg_rom[offset % prg_len] = data;
                }
            }
        }

        if (0x4500..=0x451F).contains(&address) {
            self.scratch_ram[(address & 0xFFF) as usize] = data;
        }
    }

    fn mirror_nametable(&self, cart: &Cartridge, address: u16) -> u16 {
        if (self.smc_mode & 0x02) != 0 {
            self.ciram_offset_mode(address) as u16
        } else {
            let horizontal = cart.nametable_horizontal_mirroring;
            let norm = address & 0x2FFF;
            if horizontal {
                (norm & 0x33FF) | ((norm & 0x0800) >> 1)
            } else {
                norm & 0x37FF
            }
        }
    }

    fn fetch_ppu(
        &mut self,
        _prg_rom: &[u8],
        chr_rom: &[u8],
        _prg_ram: &[u8],
        chr_ram: &[u8],
        _prg_vram: &[u8],
        using_chr_ram: bool,
        _nametable_horizontal_mirroring: bool,
        _alternative_nametable_arrangement: bool,
        ppu_address_bus: u16,
        ppu_octal_latch: u8,
        vram: &[u8],
    ) -> (u8, u16) {
        let address = (ppu_address_bus & 0x3F00) | (ppu_octal_latch as u16);
        let mut new_addr_bus = ppu_address_bus & 0xFF00;

        if address < 0x2000 {
            if (self.smc_mode & 0x05) == 0x01 {
                let bank_1k = (address >> 10) as usize;
                let offset_in_1k = address & 0x03FF;
                if (bank_1k & 3) == 3 && ((offset_in_1k & 0x3F8) == 0x3D8 || (offset_in_1k & 0x3F8) == 0x3E8) {
                    let latch_idx = (bank_1k >> 2) & 1;
                    self.latch_mmc4[latch_idx] = ((offset_in_1k >> 4) & 2) as u8;
                }
            }

            let chr_1k_bank = self.get_chr_1k_bank(address);
            let offset = chr_1k_bank * 0x400 + (address as usize & 0x3FF);
            let byte = if using_chr_ram || chr_rom.is_empty() {
                if !chr_ram.is_empty() {
                    chr_ram[offset % chr_ram.len()]
                } else {
                    0
                }
            } else {
                chr_rom[offset % chr_rom.len()]
            };
            new_addr_bus |= byte as u16;
        } else if address >= 0x2000 && address < 0x3F00 {
            let byte = if (self.smc_mode & 0x02) != 0 {
                let ciram_addr = self.ciram_offset_mode(address);
                if !vram.is_empty() {
                    vram[ciram_addr % vram.len()]
                } else {
                    0
                }
            } else {
                let nt_idx = ((address - 0x2000) >> 10) as usize;
                let reg_idx = 8 + (nt_idx & 3);
                let chr_1k_bank = self.chr_1k[reg_idx] as usize;
                let offset = chr_1k_bank * 0x400 + (address as usize & 0x3FF);
                if !chr_ram.is_empty() {
                    chr_ram[offset % chr_ram.len()]
                } else {
                    0
                }
            };
            new_addr_bus |= byte as u16;
        }

        (new_addr_bus as u8, new_addr_bus)
    }

    fn store_ppu(&mut self, cart: &mut Cartridge, address: u16, data: u8, vram: &mut [u8]) {
        self.ensure_init(cart);

        if address < 0x2000 {
            if self.mc1_mode >= 0xA0 && (self.mc1_mode & 1) == 0 {
                self.lock_chr = (self.mc1_mode & 0x10) != 0;
            }
            let protected = ((self.mc1_mode & 0xE1) >= 0x81) || self.lock_chr;
            if !protected && cart.using_chr_ram && !cart.chr_ram.is_empty() {
                let chr_1k_bank = self.get_chr_1k_bank(address);
                let offset = chr_1k_bank * 0x400 + (address as usize & 0x3FF);
                let len = cart.chr_ram.len();
                cart.chr_ram[offset % len] = data;
            }
        } else if address >= 0x2000 && address < 0x3F00 {
            if (self.smc_mode & 0x02) != 0 {
                let ciram_addr = self.ciram_offset_mode(address);
                vram[ciram_addr & 0x7FF] = data;
            } else if cart.using_chr_ram && !cart.chr_ram.is_empty() {
                let nt_idx = ((address - 0x2000) >> 10) as usize;
                let reg_idx = 8 + (nt_idx & 3);
                let chr_1k_bank = self.chr_1k[reg_idx] as usize;
                let offset = chr_1k_bank * 0x400 + (address as usize & 0x3FF);
                let len = cart.chr_ram.len();
                cart.chr_ram[offset % len] = data;
            }
        }
    }

    fn cpu_clock(&mut self, cycles: u8) -> bool {
        for _ in 0..cycles {
            if (self.fds_io & 0x80) != 0 {
                self.fds_counter = self.fds_counter.wrapping_add(3);
                while self.fds_counter >= 448 {
                    self.irq_pending = true;
                    self.fds_counter -= 448;
                }
            } else {
                self.fds_counter = 0;
            }
            if (self.smc_mode & 0x08) == 0 {
                self.clock_smc_counter();
            }
        }
        self.irq_pending
    }

    fn cpu_clock_irq_level(&self) -> bool {
        self.irq_pending
    }

    fn ppu_clock(
        &mut self,
        ppu_address_bus: u16,
        _ppu_a12_prev: bool,
        _scanline: u16,
        _dot: u16,
        _ppu_sprite_x16: bool,
        _rendering_on: bool,
    ) -> bool {
        let a12 = (ppu_address_bus & 0x1000) != 0;
        let prev_a12 = (self.smc_prev_pa & 0x1000) != 0;
        if (self.smc_mode & 0x08) != 0 && a12 && !prev_a12 {
            self.clock_smc_counter();
        }
        self.smc_prev_pa = ppu_address_bus;
        self.irq_pending
    }

    fn take_irq_ack(&mut self) -> bool {
        let ack = self.irq_ack;
        self.irq_ack = false;
        ack
    }

    fn save_mapper_registers(&self, cart: &Cartridge) -> Vec<u8> {
        let mut state = Vec::new();
        state.push(self.mc1_mode);
        state.push(self.mc2_mode);
        state.push(self.smc_mode);
        state.push(self.latch);
        state.push(if self.lock_chr { 1 } else { 0 });
        state.extend_from_slice(&self.prg_8k);
        state.extend_from_slice(&self.chr_1k);
        state.extend_from_slice(&self.latch_mmc4);
        state.push(if self.smc_irq { 1 } else { 0 });
        state.extend_from_slice(&self.smc_prev_pa.to_le_bytes());
        state.extend_from_slice(&self.smc_counter.to_le_bytes());
        state.push(self.fds_io);
        state.extend_from_slice(&self.fds_counter.to_le_bytes());
        state.push(if self.irq_pending { 1 } else { 0 });
        state.extend_from_slice(&self.scratch_ram);
        state.extend_from_slice(&cart.prg_ram);
        state
    }

    fn load_mapper_registers(&mut self, cart: &mut Cartridge, state: &[u8], mut start: usize) -> usize {
        if start + 31 <= state.len() {
            self.mc1_mode = state[start];
            self.mc2_mode = state[start + 1];
            self.smc_mode = state[start + 2];
            self.latch = state[start + 3];
            self.lock_chr = state[start + 4] != 0;
            self.prg_8k.copy_from_slice(&state[start + 5..start + 9]);
            self.chr_1k.copy_from_slice(&state[start + 9..start + 21]);
            self.latch_mmc4.copy_from_slice(&state[start + 21..start + 23]);
            self.smc_irq = state[start + 23] != 0;
            self.smc_prev_pa = u16::from_le_bytes([state[start + 24], state[start + 25]]);
            self.smc_counter = i16::from_le_bytes([state[start + 26], state[start + 27]]);
            self.fds_io = state[start + 28];
            self.fds_counter = i16::from_le_bytes([state[start + 29], state[start + 30]]);
            start += 31;
        }
        if start < state.len() {
            self.irq_pending = state[start] != 0;
            start += 1;
        }
        if start + 4096 <= state.len() {
            self.scratch_ram.copy_from_slice(&state[start..start + 4096]);
            start += 4096;
        }
        let prg_len = cart.prg_ram.len();
        if prg_len > 0 && start + prg_len <= state.len() {
            cart.prg_ram.copy_from_slice(&state[start..start + prg_len]);
            start += prg_len;
        }
        start
    }
}
